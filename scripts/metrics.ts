// node scripts/metrics.ts: writes src/metrics.ts, Instrument Sans's advance widths as Chrome measures them, so a review
// rendered in Node (src/render.ts) sizes its diagrams' boxes as the window does with a canvas.
import fs from "node:fs";
import path from "node:path";
import { chromium } from "playwright-core";

const root = path.join(import.meta.dirname, "..");
const font = fs.readFileSync(path.join(root, "web/src/fonts/instrument-sans-latin-standard-normal.woff2")).toString("base64");
const CHARS = `${String.fromCodePoint(...Array.from({ length: 95 }, (_, i) => 32 + i))}—–→←’‘“”…·×•`;

const browser = await chromium.launch({ channel: "chrome" });
const page = await browser.newPage();
await page.setContent(
  `<style>@font-face { font-family: "Instrument Sans"; src: url(data:font/woff2;base64,${font}) format("woff2"); font-weight: 400 700; font-stretch: 75% 100%; }</style>`,
);
const widths = await page.evaluate<Record<string, number[]>>(`(async () => {
  const out = {};
  for (const w of [400, 500]) {
    await document.fonts.load(w + ' 100px "Instrument Sans"');
    const c = document.createElement("canvas").getContext("2d");
    c.font = w + ' 1000px "Instrument Sans"';
    out[w] = [...${JSON.stringify(CHARS)}].map((ch) => Math.round(c.measureText(ch).width));
  }
  return out;
})()`);
await browser.close();

const body = [
  "// Generated by scripts/metrics.ts: Instrument Sans's advance widths in thousandths of an em, as Chrome's canvas measures them.",
  `export const CHARS = ${JSON.stringify(CHARS)};`,
  `export const W400 = ${JSON.stringify(widths["400"])};`,
  `export const W500 = ${JSON.stringify(widths["500"])};`,
  "",
].join("\n");
fs.writeFileSync(path.join(root, "src/metrics.ts"), body);
console.log(`wrote src/metrics.ts: ${CHARS.length} characters`);
